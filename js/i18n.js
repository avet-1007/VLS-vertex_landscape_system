const I18N_LANGS = ["en", "ru", "hy", "zh", "ar"];
const I18N_RTL = ["ar"];

let LANG = (typeof localStorage !== "undefined" && localStorage.getItem("vls_lang")) || "en";
if (I18N_LANGS.indexOf(LANG) < 0) LANG = "en";

function tr(key) {
  const dict = I18N[LANG] || I18N.en;
  let s = dict[key];
  if (s == null) s = I18N.en[key] != null ? I18N.en[key] : key;
  const args = Array.prototype.slice.call(arguments, 1);
  return s.replace(/\{(\d+)\}/g, function (m, i) { return args[+i] != null ? String(args[+i]) : m; });
}

function setLang(l) {
  LANG = I18N_LANGS.indexOf(l) >= 0 ? l : "en";
  try { localStorage.setItem("vls_lang", LANG); } catch (e) { }
  try {
    const de = document.documentElement;
    de.setAttribute("lang", LANG);
    de.setAttribute("dir", I18N_RTL.indexOf(LANG) >= 0 ? "rtl" : "ltr");
  } catch (e) { }
  applyStaticLang();
  // the texture department builds its own strings at runtime — rebuild it after a switch
  if (typeof refreshTexPanel === "function" && typeof texMode === "function" && texMode()) refreshTexPanel();
  const se = document.getElementById("langSel");
  if (se) se.value = LANG;
}

function applyStaticLang() {
  const txt = document.querySelectorAll("[data-i18n]");
  for (let i = 0; i < txt.length; i++) txt[i].textContent = tr(txt[i].getAttribute("data-i18n"));
  const tit = document.querySelectorAll("[data-i18n-title]");
  for (let i = 0; i < tit.length; i++) tit[i].title = tr(tit[i].getAttribute("data-i18n-title"));
  const ph = document.querySelectorAll("[data-i18n-ph]");
  for (let i = 0; i < ph.length; i++) ph[i].placeholder = tr(ph[i].getAttribute("data-i18n-ph"));
  const lb = document.querySelectorAll("[data-i18n-label]");
  for (let i = 0; i < lb.length; i++) lb[i].dataset.label = tr(lb[i].getAttribute("data-i18n-label"));
  // the hotkey rows are built at runtime — rebuild them together with the language
  if (typeof renderKeybinds === "function") renderKeybinds();
}

// Init: language from settings, static text by keys
setLang(LANG);
